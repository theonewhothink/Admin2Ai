"""QA: the 50 real-world SME case studies and the universal client acceptance checklist.

The acceptance document defines what "100/100" means in practice: 50 production
acceptance scenarios and a checklist of 204 checks in 21 sections (A to U), plus a
final 30-day test. This module is that document as data, with an honest verdict for
every check, and the internal dashboard's QA page shows it
(``GET /api/internal/acceptance``). The cases also need sector capabilities the
checklist does not name (payouts, cost centers, deposits, ...): those are the X checks.

Verdicts
--------
``pass``     works in the engine and is proven by at least one named automated test.
``partial``  some of it works, or it is built but not connected, or it needs
             accounts or keys the product does not have yet.
``missing``  not built.

``tests/test_acceptance.py`` keeps the verdicts honest: every ``pass`` must cite a
test that exists (a Python test function, or a mobile ``it("...")`` case), every
cited file must exist, and every case must point only at checks defined here.
Whoever changes what the product can do updates the verdict here in the same change.

A case passes only when its PASS test is met *and* everything it must handle passes.
Its PASS test is met when every check that test depends on passes; it is not met
when none of them is built.
"""

