# --------------------------------------------------------------------------- verdicts

def _combine(statuses: list[Status]) -> Status:
    if statuses and all(s == "pass" for s in statuses):
        return "pass"
    if statuses and all(s == "missing" for s in statuses):
        return "missing"
    return "partial"


def _check_row(c: Check) -> dict[str, Any]:
    return {"id": c.id, "text": c.text, "status": c.status, "where": c.where, "note": c.note,
            "evidence": list(c.evidence)}


def _counts(statuses: list[Status]) -> dict[str, int]:
    return {"pass": statuses.count("pass"), "partial": statuses.count("partial"),
            "missing": statuses.count("missing"), "total": len(statuses)}


def _case_row(k: Case) -> dict[str, Any]:
    decisive = [CHECKS[i].status for i in k.decisive]
    pass_test = _combine(decisive)
    handled = [CHECKS[ref].status for _, ref in k.handles]
    covered = handled.count("pass")
    if pass_test == "pass" and covered == len(handled):
        verdict: Status = "pass"
    elif pass_test == "missing":
        verdict = "missing"
    else:
        verdict = "partial"
    gaps = []
    seen: set[str] = set()
    for text, ref in k.handles:
        c = CHECKS[ref]
        if c.status != "pass" and ref not in seen:
            seen.add(ref)
            gaps.append({"id": ref, "text": c.text, "status": c.status, "note": c.note})
    for ref in k.decisive:
        c = CHECKS[ref]
        if c.status != "pass" and ref not in seen:
            seen.add(ref)
            gaps.append({"id": ref, "text": c.text, "status": c.status, "note": c.note})
    return {
        "number": k.number, "title": k.title, "quote": k.quote, "verdict": verdict,
        "passTest": {"text": k.pass_test, "status": pass_test,
                     "checks": [{"id": i, "text": CHECKS[i].text, "status": CHECKS[i].status} for i in k.decisive]},
        "handles": [{"text": text, "check": ref, "status": CHECKS[ref].status, "where": CHECKS[ref].where,
                     "note": CHECKS[ref].note} for text, ref in k.handles],
        "covered": covered, "handled": len(handled),
        "gaps": gaps,
    }


def acceptance() -> dict[str, Any]:
    """The QA page: every case and check with its verdict and the totals (JSON-able)."""
    sections = []
    all_checks: list[Status] = []
    for letter, title, checks in SECTIONS:
        statuses = [c.status for c in checks]
        all_checks += statuses
        sections.append({"id": letter, "title": title, "counts": _counts(statuses),
                         "checks": [_check_row(c) for c in checks]})
    cases = [_case_row(k) for k in CASES]
    verdicts = [c["verdict"] for c in cases]
    pass_tests = [c["passTest"]["status"] for c in cases]
    checklist = _counts(all_checks)
    return {
        "purpose": PURPOSE,
        "legend": {
            "pass": "Works in the engine and is proven by a named automated test.",
            "partial": "Some of it works, or it is built but not connected, or it needs accounts or keys.",
            "missing": "Not built.",
        },
        "summary": {
            "cases": _counts(verdicts),
            "passTests": _counts(pass_tests),
            "checklist": checklist,
            "percent": checklist["pass"] * 100 // checklist["total"] if checklist["total"] else 0,
            "sector": _counts([c.status for c in EXTRA]),
        },
        "sections": sections,
        "sector": [_check_row(c) for c in EXTRA],
        "cases": cases,
        "finalTest": FINAL_TEST,
    }
