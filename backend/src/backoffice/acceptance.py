NOWHERE = "Nowhere yet"


@dataclass(frozen=True, slots=True)
class Check:
    id: str
    text: str
    status: Status
    where: str
    note: str
    evidence: tuple[str, ...]


@dataclass(frozen=True, slots=True)
class Case:
    number: int
    title: str
    quote: str
    handles: tuple[tuple[str, str], ...]  # (what the case must handle, check id)
    pass_test: str
    decisive: tuple[str, ...]  # the checks the PASS test depends on


def _c(id_: str, text: str, status: Status, where: str, note: str = "", *evidence: str) -> Check:
    return Check(id_, text, status, where, note, tuple(evidence))


